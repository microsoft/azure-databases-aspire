    /// <summary>
    /// Adds a DocumentDB resource to the application model. A container is used for local development.
    /// </summary>
    /// <remarks>
    /// This resource includes a built-in health check. When this resource is referenced as a dependency
    /// using the <see cref="ResourceBuilderExtensions.WaitFor{T}(IResourceBuilder{T}, IResourceBuilder{IResource})"/>
    /// extension method then the dependent resource will wait until the DocumentDB server responds to ping.
    /// This version of the package defaults to the <inheritdoc cref="DocumentDBContainerImageTags.Tag"/> tag of the <inheritdoc cref="DocumentDBContainerImageTags.Image"/> container image.
    /// </remarks>
    /// <param name="builder">The <see cref="IDistributedApplicationBuilder"/>.</param>
    /// <param name="name">The name of the resource. This name will be used as the connection string name when referenced in a dependency.</param>
    /// <param name="port">The host port for DocumentDB.</param>
    /// <returns>A reference to the <see cref="IResourceBuilder{T}"/>.</returns>
    /// <example>
    /// <code>
    /// var server = builder.AddDocumentDB("documentdb", port: 10260);
    /// </code>
    /// </example>
    public static IResourceBuilder<DocumentDBServerResource> AddDocumentDB(this IDistributedApplicationBuilder builder, [ResourceName] string name, int? port)
        => AddDocumentDB(builder, name, port, null, null);

    /// <summary>
    /// <inheritdoc cref="AddDocumentDB(IDistributedApplicationBuilder, string, int?)"/>
    /// </summary>
    /// <param name="builder">The <see cref="IDistributedApplicationBuilder"/>.</param>
    /// <param name="name">The name of the resource. This name will be used as the connection string name when referenced in a dependency.</param>
    /// <param name="port">The host port for DocumentDB.</param>
    /// <param name="userName">A parameter that contains the DocumentDB server user name, or <see langword="null"/> to use a default value.</param>
    /// <param name="password">A parameter that contains the DocumentDB server password, or <see langword="null"/> to use a generated password.</param>
    /// <returns>A reference to the <see cref="IResourceBuilder{T}"/>.</returns>
    /// <example>
    /// <code>
    /// // Minimal usage with generated credentials:
    /// var server = builder.AddDocumentDB("documentdb");
    /// var database = server.AddDatabase("mydb");
    ///
    /// // With custom credentials:
    /// var user = builder.AddParameter("db-user");
    /// var pass = builder.AddParameter("db-pass", secret: true);
    /// var securedServer = builder.AddDocumentDB("documentdb", userName: user, password: pass);
    /// </code>
    /// </example>
    public static IResourceBuilder<DocumentDBServerResource> AddDocumentDB(this IDistributedApplicationBuilder builder,
        string name,
        int? port = null,
        IResourceBuilder<ParameterResource>? userName = null,
        IResourceBuilder<ParameterResource>? password = null)
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentException.ThrowIfNullOrEmpty(name);

        var passwordParameter = password?.Resource ?? ParameterResourceBuilderExtensions.CreateDefaultPasswordParameter(builder, $"{name}-password", special: false);

        var DocumentDBContainer = new DocumentDBServerResource(name, userName?.Resource, passwordParameter);

        // One hook per application, however many DocumentDB resources it has: the hook walks the
        // model rather than closing over a resource. See DocumentDBImageSealLifecycleHook.
#pragma warning disable CS0618 // The lifecycle-hook phase has no eventing equivalent that runs after every BeforeStartEvent subscriber.
        builder.Services.TryAddLifecycleHook<DocumentDBImageSealLifecycleHook>();
#pragma warning restore CS0618

        string? connectionString = null;

        builder.Eventing.Subscribe<ConnectionStringAvailableEvent>(DocumentDBContainer, async (@event, ct) =>
        {
            connectionString = await DocumentDBContainer.ConnectionStringExpression.GetValueAsync(ct).ConfigureAwait(false)
                ?? throw new DistributedApplicationException($"ConnectionStringAvailableEvent was published for the '{DocumentDBContainer.Name}' resource but the connection string was null.");
        });

        var healthCheckKey = $"{name}_check";
        // Use a database-scoped check so the MongoDB health check package executes a ping command.
        IMongoDatabase? database = null;
        builder.Services.AddHealthChecks()
            .AddMongoDb(
                _ => database ??=
                    new MongoClient(connectionString ?? throw new InvalidOperationException("Connection string is unavailable"))
                        .GetDatabase(DefaultHealthCheckDatabaseName),
                name: healthCheckKey);

        return builder
            .AddResource(DocumentDBContainer)
            .WithEndpoint(port: port, targetPort: DefaultContainerPort, name: DocumentDBServerResource.PrimaryEndpointName)
            .WithImage(DocumentDBContainerImageTags.Image, DocumentDBContainerImageTags.Tag)
            .WithImageRegistry(DocumentDBContainerImageTags.Registry)
            .WithEnvironment(context =>
            {
                context.EnvironmentVariables[UserEnvVarName] = DocumentDBContainer.UserNameReference;
                context.EnvironmentVariables[PasswordEnvVarName] = DocumentDBContainer.PasswordParameter!;
            })
            .WithHealthCheck(healthCheckKey)
            .SubscribeMinimumPgVariantImageGuard()
            .SubscribeDataStorageGuard();
    }

    /// <summary>
    /// Subscribes a <see cref="BeforeResourceStartedEvent"/> handler that throws
    /// <see cref="InvalidOperationException"/> when the resource's effective image tag names a
    /// PostgreSQL backend variant upstream does not publish for that DocumentDB version — see
    /// <see cref="DocumentDBContainerImageTags.MinimumVersionByPgVariant"/>.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Subscribed from <c>AddDocumentDB</c> rather than from <see cref="WithPostgresVersion"/>,
    /// because neither half of the tag is a problem on its own and the documented precedence is
    /// "last call wins": selecting <c>Pg18</c> before <c>V0_114_0</c> is perfectly legitimate,
    /// so only the effective tag at start time can be judged.
    /// </para>
    /// <para>
    /// Same carve-outs as <see cref="SubscribeMinimumPostgresImageGuard"/>: custom images, tags
    /// outside the strict <c>pg{NN}-X.Y.Z</c> grammar and caller-owned Dockerfile builds are
    /// exempt, and the guard is run-mode only, so manifest generation is unaffected. Unlike that
    /// guard this one is always subscribed, so the exempt paths stay silent rather than warning on
    /// every app that pins a custom image.
    /// </para>
    /// </remarks>
    private static IResourceBuilder<DocumentDBServerResource> SubscribeMinimumPgVariantImageGuard(
        this IResourceBuilder<DocumentDBServerResource> builder)
    {
        builder.ApplicationBuilder.Eventing.Subscribe<BeforeResourceStartedEvent>(
            builder.Resource,
            (evt, ct) =>
            {
                // The image the orchestrator prepared, not the annotation as it now reads.
                VerifyImageSeal(evt.Resource);

                // Only a curated image is pulled by tag from the upstream registry. A fork
                // publishing its own images decides its own variant matrix, and a resource built
                // from the caller's own Dockerfile never resolves that tag at all.
                var image = ResolveEffectiveImage(evt.Resource);
                if (image is not { Origin: DocumentDBImageOrigin.Curated, KnownVersion: { } docVersion })
                {
                    return Task.CompletedTask;
                }

                if (!DocumentDBContainerImageTags.MinimumVersionByPgVariant.TryGetValue(image.PostgresVariant, out var minimum) ||
                    docVersion >= minimum)
                {
                    return Task.CompletedTask;
                }

                throw new InvalidOperationException(
                    $"DocumentDB resource '{evt.Resource.Name}' resolves to image tag " +
                    $"'{image.Tag}', but upstream only publishes pg{image.PostgresVariant} images " +
                    $"from DocumentDB v{minimum} onwards. That tag does not exist on " +
                    $"{DocumentDBContainerImageTags.Registry}/{DocumentDBContainerImageTags.Image}, " +
                    $"so starting the resource would fail with an opaque manifest-not-found error. " +
                    $"Recovery: pair " +
                    $"'.WithPostgresVersion(DocumentDBPostgresVersion.Pg{image.PostgresVariant})' " +
                    $"with DocumentDB v{minimum} or newer, or choose a PostgreSQL variant that " +
                    $"exists for v{docVersion}.");
            });

        return builder;
    }

    /// <summary>
    /// How much this package can know about the container image a DocumentDB resource will
    /// actually run.
    /// </summary>
    private enum DocumentDBImageOrigin
    {
        /// <summary>The resource carries no <see cref="ContainerImageAnnotation"/> at all.</summary>
        None,

        /// <summary>
        /// The image is the output of a container build the caller owns, so nothing this package
        /// documents about a published DocumentDB release has been established for it.
        /// </summary>
        DockerfileBuild,

        /// <summary>A repository other than the curated <c>documentdb-local</c> one.</summary>
        CustomRepository,

        /// <summary>
        /// The curated repository, with a tag outside the strict <c>pg{NN}-X.Y.Z</c> grammar.
        /// </summary>
        UnrecognizedTag,

        /// <summary>
        /// The curated repository, pinned by digest. The digest is what the runtime resolves, so
        /// the version is unknown whatever tag the reference also carries.
        /// </summary>
        DigestPinned,

        /// <summary>
        /// The curated repository with a tag this build recognises — the only origin that carries
        /// a DocumentDB version.
        /// </summary>
        Curated,
    }

    /// <summary>
    /// What this package knows about the container image a DocumentDB resource will run.
    /// </summary>
    /// <remarks>
    /// <see cref="KnownVersion"/> and <see cref="PostgresVariant"/> are populated only when
    /// <see cref="Origin"/> is <see cref="DocumentDBImageOrigin.Curated"/>, which in particular
    /// means never when a <see cref="Digest"/> is present. Every version-dependent decision in
    /// this package is therefore gated on <c>KnownVersion is { } version</c>: one place decides
    /// what is known, and no caller can conclude a version from an image whose version is not
    /// known.
    /// </remarks>
    /// <param name="Origin">How much is known about the image.</param>
    /// <param name="Image">
    /// The repository as the annotation spells it, for diagnostics. It is not the identity: see
    /// <see cref="DocumentDBContainerImageTags.NamesCuratedRepository"/>.
    /// </param>
    /// <param name="Tag">The effective tag, whether the annotation or the reference carried it.</param>
    /// <param name="Digest">
    /// The effective digest, whether the annotation or the reference carried it, without its
    /// algorithm prefix.
    /// </param>
    /// <param name="PostgresVariant">The PostgreSQL major version of a curated tag.</param>
    /// <param name="KnownVersion">The DocumentDB version of a curated tag.</param>
    private readonly record struct DocumentDBEffectiveImage(
        DocumentDBImageOrigin Origin,
        string? Image,
        string? Tag,
        string? Digest,
        int PostgresVariant,
        Version? KnownVersion);

    /// <summary>
    /// Resolves what this package knows about the container image <paramref name="resource"/>
    /// will actually run.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A container build the caller owns is decided first and unconditionally, because for such a
    /// resource the image annotation does not describe what runs. Aspire keeps the
    /// <see cref="ContainerImageAnnotation"/> that <c>AddDocumentDB</c> installs when
    /// <c>WithDockerfile(...)</c> is chained onto the resource, and a caller may also point that
    /// annotation at the official repository and tag afterwards, so a Dockerfile-built resource
    /// can be annotated indistinguishably from an official release while running an image built
    /// from an arbitrary <c>Dockerfile</c> — one that merely inherits the official image as its
    /// base, or does not use it at all. What runs is the build output: the manifest emits
    /// <c>build</c> instead of <c>image</c>, and in run mode the orchestrator builds the context
    /// before starting the container. None of the release properties this package acts on — the
    /// <c>/data</c> volume declaration, the data-directory <c>flock</c>, the PostgreSQL credential
    /// pass-through, the gateway configuration layout and entrypoint — has been proven for such an
    /// image, so it is classified as unknown rather than granted them on the strength of a label.
    /// </para>
    /// <para>
    /// <see cref="DockerfileBuildAnnotation"/> is the single authoritative signal, and one check
    /// covers every entry point: <c>WithDockerfile</c>, <c>WithDockerfileFactory</c> and
    /// <c>WithDockerfileBuilder</c> all add it — the last adds a
    /// <c>DockerfileBuilderCallbackAnnotation</c> beside it, not instead of it.
    /// <c>DockerfileBaseImageAnnotation</c> on its own is not a build: it selects base images for
    /// a <em>generated</em> Dockerfile, and with no build to generate one it changes neither the
    /// image a container resource pulls nor the manifest it publishes.
    /// </para>
    /// <para>
    /// Everything else is decided on the reference Aspire composes rather than on
    /// <see cref="ContainerImageAnnotation.Image"/> alone, because the boundary between registry
    /// and repository is the caller's to move: see
    /// <see cref="DocumentDBContainerImageTags.NamesCuratedRepository"/>. A tag or digest the
    /// annotation supplies wins over one written into the reference, and two tags in one reference
    /// are contradictory — Aspire emits <c>repo:a:b</c>, which resolves to nothing — so neither is
    /// trusted.
    /// </para>
    /// <para>
    /// A digest beats every tag. A reference may carry both — <c>repo:pg17-0.116.0@sha256:...</c>,
    /// or an inline tag beside an annotation <c>SHA256</c>, or the reverse — and the runtime
    /// resolves the digest and ignores the tag, so the tag names whichever release the caller
    /// last typed rather than the image that starts. Reading a version out of it would let an
    /// image predating the <c>/data</c> volume, the data-directory <c>flock</c> or a credential
    /// floor inherit the promises of a release it is not. So any digest at all classifies the
    /// resource as <see cref="DocumentDBImageOrigin.DigestPinned"/>, which carries no version;
    /// the repository is still known, which is what lets the telemetry API reject the pin with a
    /// message instead of silently skipping it.
    /// </para>
    /// </remarks>
    private static DocumentDBEffectiveImage ResolveModelImage(IResource resource)
    {
        var image = resource.Annotations.OfType<ContainerImageAnnotation>().LastOrDefault();

        if (resource.Annotations.OfType<DockerfileBuildAnnotation>().Any())
        {
            return new(DocumentDBImageOrigin.DockerfileBuild, image?.Image, image?.Tag, image?.SHA256, 0, null);
        }

        if (image is null)
        {
            return new(DocumentDBImageOrigin.None, null, null, null, 0, null);
        }

        var curated = DocumentDBContainerImageTags.NamesCuratedRepository(
            image.Registry, image.Image, out var inlineTag, out var inlineDigest);

        var tag = string.IsNullOrEmpty(image.Tag) ? inlineTag : image.Tag;
        var digest = string.IsNullOrEmpty(image.SHA256) ? inlineDigest : image.SHA256;

        // Two tags in one reference contradict each other. A digest given twice needs no such
        // rule: any digest at all already forces the version unknown.
        var ambiguousTag = !string.IsNullOrEmpty(image.Tag) && inlineTag is not null;

        if (!curated)
        {
            return new(DocumentDBImageOrigin.CustomRepository, image.Image, tag, digest, 0, null);
        }

        if (!string.IsNullOrEmpty(digest))
        {
            return new(DocumentDBImageOrigin.DigestPinned, image.Image, tag, digest, 0, null);
        }

        if (ambiguousTag ||
            !DocumentDBContainerImageTags.TryParseDocumentDBTag(tag, out var pg, out var version))
        {
            return new(DocumentDBImageOrigin.UnrecognizedTag, image.Image, tag, digest, 0, null);
        }

        return new(DocumentDBImageOrigin.Curated, image.Image, tag, digest, pg, version);
    }

    /// <summary>
    /// What this package knows about the image the resource will really run, judged on the seal a
    /// run takes before the orchestrator prepares anything and on the live model when there is
    /// none.
    /// </summary>
    /// <remarks>
    /// Every version-dependent decision in this package goes through here, so all of them judge
    /// one image: the one the container runtime is committed to. See
    /// <see cref="DocumentDBImageSealLifecycleHook"/> for why the model on its own is not that
    /// image, and <see cref="ResolveModelImage"/> for the live reading, which only the seal itself
    /// and the check that the model still agrees with it are allowed to use.
    /// </remarks>
    private static DocumentDBEffectiveImage ResolveEffectiveImage(IResource resource) =>
        resource.Annotations.OfType<DocumentDBImageSealAnnotation>().LastOrDefault() is { } seal
            ? seal.Image
            : ResolveModelImage(resource);

    /// <summary>
    /// The image and build origin a run has been committed to, recorded at the last phase before
    /// the orchestrator reads them.
    /// </summary>
    private sealed class DocumentDBImageSealAnnotation(
        DocumentDBEffectiveImage image,
        string? reference,
        System.Collections.Immutable.ImmutableArray<DockerfileBuildAnnotation> build) : IResourceAnnotation
    {
        /// <summary>What this package knows about the sealed image.</summary>
        public DocumentDBEffectiveImage Image { get; } = image;

        /// <summary>
        /// The image reference exactly as Aspire composes it for the container spec —
        /// <see cref="ResourceExtensions.TryGetContainerImageName(IResource, out string?)"/> — so
        /// the seal is literally the string the orchestrator snapshots rather than a
        /// re-derivation of it.
        /// </summary>
        public string? Reference { get; } = reference;

        /// <summary>
        /// The build definitions the resource carried, by identity and in order. They decide both
        /// what <see cref="Reference"/> resolves to and whether the image is a published release
        /// at all, and a replacement can leave the reference untouched.
        /// </summary>
        public System.Collections.Immutable.ImmutableArray<DockerfileBuildAnnotation> Build { get; } = build;
    }

    /// <summary>
    /// Seals the image every DocumentDB resource in the model will run, at the last phase that is
    /// guaranteed to precede the orchestrator's own reading of it.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Aspire snapshots a container's image into the DCP container spec while it prepares
    /// resources — <c>ContainerCreator.PrepareObjects()</c> calls
    /// <see cref="ResourceExtensions.TryGetContainerImageName(IResource, out string?)"/> once and
    /// creates the spec from the result — and nothing re-reads
    /// <see cref="ContainerImageAnnotation"/> for it afterwards. That preparation happens before
    /// endpoints are allocated, so <see cref="ResourceEndpointsAllocatedEvent"/>,
    /// <see cref="BeforeResourceStartedEvent"/> and the container-runtime-argument callbacks all
    /// run after the image is already fixed. A check that read the annotation at any of those
    /// phases would be judging a different image from the one being started: raising the tag from
    /// a subscriber makes a floor pass while the old image starts, and lowering it makes this
    /// package promise a data-directory interlock the running release does not have.
    /// </para>
    /// <para>
    /// <see cref="IDistributedApplicationLifecycleHook.BeforeStartAsync"/> is the answer rather
    /// than <see cref="BeforeStartEvent"/>: Aspire publishes that event, then runs every lifecycle
    /// hook, then the before-start pipeline, and only then starts the host and the orchestrator. A
    /// hook therefore runs after every <see cref="BeforeStartEvent"/> subscriber — including ones
    /// registered after <c>AddDocumentDB</c>, which is exactly where ordinary late configuration
    /// lives — and still strictly before anything is prepared. Configuration written before that
    /// point is ordinary and is sealed as it stands; a change made after it is refused by
    /// <see cref="VerifyImageSeal"/>.
    /// </para>
    /// <para>
    /// Run mode only. A publish never prepares a container: the manifest is written from the model
    /// at serialization time, which is later than every lifecycle phase, so there the model is the
    /// authority and sealing it would report ordinary publish-time configuration as a change. What
    /// protects a publish is the manifest checkpoint, which judges the resource while it is being
    /// serialized.
    /// </para>
    /// </remarks>
#pragma warning disable CS0618 // The lifecycle-hook phase has no eventing equivalent that runs after every BeforeStartEvent subscriber.
    private sealed class DocumentDBImageSealLifecycleHook(DistributedApplicationExecutionContext executionContext)
        : IDistributedApplicationLifecycleHook
    {
        public Task BeforeStartAsync(DistributedApplicationModel appModel, CancellationToken cancellationToken = default)
        {
            if (!executionContext.IsRunMode)
            {
                return Task.CompletedTask;
            }

            foreach (var resource in appModel.Resources.OfType<DocumentDBServerResource>())
            {
                SealLaunchImage(resource);
            }

            return Task.CompletedTask;
        }
    }
#pragma warning restore CS0618

    private static void SealLaunchImage(DocumentDBServerResource resource)
    {
        if (resource.Annotations.OfType<DocumentDBImageSealAnnotation>().Any())
        {
            return;
        }

        resource.Annotations.Add(new DocumentDBImageSealAnnotation(
            ResolveModelImage(resource),
            resource.TryGetContainerImageName(out var reference) ? reference : null,
            [.. resource.Annotations.OfType<DockerfileBuildAnnotation>()]));
    }

    /// <summary>
    /// Fails the resource when its image or build origin no longer matches the one the run was
    /// sealed on.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Called from the checkpoints that run after the seal and cannot be cached: the
    /// container-runtime-arguments callback, which Aspire re-invokes on every container creation,
    /// and the per-resource start event, which is where a caller sees the failure reported against
    /// the resource. Nothing is repaired: the spec the orchestrator holds was built from the sealed
    /// reference and cannot be rewritten from here, so the only honest outcome is to refuse to
    /// start rather than to run one image while every rule in this package judged another.
    /// </para>
    /// <para>
    /// Image references are configuration, not credentials, so both are named: knowing which two
    /// images disagree is the whole content of the diagnostic.
    /// </para>
    /// </remarks>
    private static void VerifyImageSeal(IResource resource)
    {
        if (resource.Annotations.OfType<DocumentDBImageSealAnnotation>().LastOrDefault() is not { } seal)
        {
            return;
        }

        var reference = resource.TryGetContainerImageName(out var current) ? current : null;

        var change =
            !string.Equals(reference, seal.Reference, StringComparison.Ordinal)
                ? "the image reference it will run changed"
            : !SameBuildOrigin(resource, seal)
                ? "the container build it is produced by was added, removed or replaced"
            : !ResolveModelImage(resource).Equals(seal.Image)
                ? "the release the image names changed"
            : null;

        if (change is null)
        {
            return;
        }

        throw new InvalidOperationException(
            $"DocumentDB resource '{resource.Name}' was changed after the image it will run had " +
            $"already been settled: {change}. Aspire snapshots a container's image into the " +
            $"orchestrator's container spec while it prepares resources, which is before endpoints " +
            $"are allocated and before the resource-start event, so a change made after that point " +
            $"lands in the model but not in the container that is created: the container would run " +
            $"'{seal.Reference ?? "<none>"}' while this package judged " +
            $"'{reference ?? "<none>"}' — its version floors, its data-directory interlock and its " +
            $"declared-volume advice would all describe an image that is not the one starting. The " +
            $"resource is failed instead. Recovery: choose the image while the application model is " +
            $"being built (WithImage(...), WithImageTag(...), WithImageRegistry(...), " +
            $"WithImageSHA256(...), WithDockerfile(...)), or at the latest from a BeforeStartEvent " +
            $"subscriber, rather than from a ResourceEndpointsAllocatedEvent or " +
            $"BeforeResourceStartedEvent subscriber or an IDistributedApplicationLifecycleHook that " +
            $"runs after this package's.");
    }

    /// <summary>
    /// Compares the build definitions by identity, in order. Identity rather than value, because a
    /// replacement can be indistinguishable by value and still carry a different Dockerfile
    /// factory; order, because Aspire builds from the single build annotation a resource carries
    /// and refuses the resource outright when there is more than one, so no legitimate reordering
    /// exists.
    /// </summary>
    private static bool SameBuildOrigin(IResource resource, DocumentDBImageSealAnnotation seal)
    {
        var current = resource.Annotations.OfType<DockerfileBuildAnnotation>().ToArray();

        if (current.Length != seal.Build.Length)
        {
            return false;
        }

        for (var index = 0; index < current.Length; index++)
        {
            if (!ReferenceEquals(current[index], seal.Build[index]))
            {
                return false;
            }
        }

        return true;
    }

    /// <summary>
    /// Adds a DocumentDB database to the application model.
    /// </summary>
    /// <remarks>
    /// The database resource inherits the parent server's connection string and appends the database name.
    /// Services should reference the database resource (not the server) via <c>.WithReference(db)</c>.
    /// This resource includes a built-in health check. When this resource is referenced as a dependency
    /// using the <see cref="ResourceBuilderExtensions.WaitFor{T}(IResourceBuilder{T}, IResourceBuilder{IResource})"/>
    /// extension method then the dependent resource will wait until the DocumentDB database responds to ping.
    /// </remarks>
    /// <param name="builder">The DocumentDB server resource builder.</param>
    /// <param name="name">The name of the resource. This name will be used as the connection string name when referenced in a dependency.</param>
    /// <param name="databaseName">The name of the database. If not provided, this defaults to the same value as <paramref name="name"/>.</param>
    /// <returns>A reference to the <see cref="IResourceBuilder{T}"/>.</returns>
    /// <example>
    /// <code>
    /// var server = builder.AddDocumentDB("documentdb");
    /// var ordersDb = server.AddDatabase("orders");
    /// var usersDb = server.AddDatabase("users");
    /// </code>
    /// </example>
    public static IResourceBuilder<DocumentDBDatabaseResource> AddDatabase(this IResourceBuilder<DocumentDBServerResource> builder, [ResourceName] string name, string? databaseName = null)
    {
        ArgumentNullException.ThrowIfNull(builder);
        ArgumentException.ThrowIfNullOrEmpty(name);

        // Use the resource name as the database name if it's not provided
        databaseName ??= name;

        var DocumentDBDatabase = new DocumentDBDatabaseResource(name, databaseName, builder.Resource);
        builder.Resource.AddDatabase(DocumentDBDatabase);

        string? connectionString = null;

        builder.ApplicationBuilder.Eventing.Subscribe<ConnectionStringAvailableEvent>(DocumentDBDatabase, async (@event, ct) =>
        {
            connectionString = await DocumentDBDatabase.ConnectionStringExpression.GetValueAsync(ct).ConfigureAwait(false)
                ?? throw new DistributedApplicationException($"ConnectionStringAvailableEvent was published for the '{DocumentDBDatabase.Name}' resource but the connection string was null.");
        });

        var healthCheckKey = $"{name}_check";
        // cache the database instance so it is reused on subsequent calls to the health check
        IMongoDatabase? database = null;
        builder.ApplicationBuilder.Services.AddHealthChecks()
            .AddMongoDb(
                _ => database ??=
                    new MongoClient(connectionString ?? throw new InvalidOperationException("Connection string is unavailable"))
                        .GetDatabase(databaseName),
                name: healthCheckKey);

        return builder.ApplicationBuilder
            .AddResource(DocumentDBDatabase)
            .WithHealthCheck(healthCheckKey)
            .InstallDatabaseManifestCheckpoint();
    }

    /// <summary>
    /// Installs the checkpoint that judges a database's published connection string while the
    /// database is being serialized.
    /// </summary>
    /// <remarks>
    /// <para>
    /// A database's manifest entry is a connection string and nothing else, and that string is
    /// built from the parent server's TLS settings —
    /// <see cref="DocumentDBServerResource.BuildConnectionString"/> — so the same mutation the
    /// server's checkpoint exists to catch changes what every child publishes too. The two are
    /// written as separate entries, and writing either of them can run a callback that changes the
    /// other: Aspire pulls a resource referenced by a connection string into the manifest while
    /// writing the entry that references it, and the server's own entry evaluates its environment
    /// callbacks. So the child is checked where the child is written rather than only where the
    /// parent is.
    /// </para>
    /// <para>
    /// The checkpoint holds the position the publisher reads — last — and hands the writing on to
    /// whatever it displaced, so the entry is byte-for-byte the one Aspire would have produced: a
    /// caller's own <c>WithManifestPublishingCallback(...)</c> still writes it, and
    /// <c>ExcludeFromManifest()</c> still excludes it, because a resource that emits nothing
    /// publishes no connection string to judge.
    /// </para>
    /// </remarks>
    private static IResourceBuilder<DocumentDBDatabaseResource> InstallDatabaseManifestCheckpoint(
        this IResourceBuilder<DocumentDBDatabaseResource> builder)
    {
        var resource = builder.Resource;
        ManifestPublishingCallbackAnnotation? checkpoint = null;

        checkpoint = new ManifestPublishingCallbackAnnotation(async context =>
        {
            var security = CaptureConnectionStringSecurity(resource.Parent, resource);

            var displaced = resource.Annotations.OfType<ManifestPublishingCallbackAnnotation>()
                .LastOrDefault(annotation => !ReferenceEquals(annotation, checkpoint));

            if (displaced is null)
            {
                // What Aspire writes for an IResourceWithConnectionString that is not a container,
                // an executable, a project or a parameter.
                context.Writer.WriteString("type", "value.v0");
                context.WriteConnectionString(resource);
            }
            else if (displaced.Callback is { } callback)
            {
                await callback(context).ConfigureAwait(false);
            }

            VerifyDatabaseConnectionStringUnchanged(resource, security);
        });

        resource.Annotations.Add(checkpoint);

        // ExcludeFromManifest() and WithManifestPublishingCallback() both append after this, and
        // the publisher reads only the last annotation, so the position is taken back at the two
        // phases a publish raises before it serializes anything.
        builder.ApplicationBuilder.Eventing.Subscribe<BeforeStartEvent>((_, _) =>
        {
            EstablishManifestCheckpoint(resource, checkpoint);
            return Task.CompletedTask;
        });

        builder.ApplicationBuilder.Eventing.Subscribe<Publishing.BeforePublishEvent>((_, _) =>
        {
            EstablishManifestCheckpoint(resource, checkpoint);
            return Task.CompletedTask;
        });

        return builder;
    }

    /// <summary>
    /// Fails the publish when a database's published connection string, or the TLS state behind it,
    /// changed while its entry was being written.
    /// </summary>
    /// <remarks>
    /// Nothing is repaired: the string is already in the writer and cannot be taken back. No value
    /// is reported either — the connection string carries the resource's credentials, and the name
    /// of what changed is the whole of what is safe and the whole of what is useful.
    /// </remarks>
    private static void VerifyDatabaseConnectionStringUnchanged(
        DocumentDBDatabaseResource resource,
        ConnectionStringSecuritySnapshot before)
    {
        var after = CaptureConnectionStringSecurity(resource.Parent, resource);

        var change =
            after.Tls != before.Tls
                ? "whether it uses TLS changed"
            : after.AllowInsecureTls != before.AllowInsecureTls
                ? "whether it accepts an invalid TLS certificate changed"
            : !string.Equals(after.Expression, before.Expression, StringComparison.Ordinal)
                ? "the connection string itself changed"
            : null;

        if (change is null)
        {
            return;
        }

        throw new InvalidOperationException(
            $"DocumentDB database resource '{resource.Name}' was changed while its manifest entry " +
            $"was being written: {change}. A database publishes nothing but the connection string " +
            $"its parent server '{resource.Parent.Name}' builds, and Aspire writes that string " +
            $"before it evaluates any environment callback, so a change made from inside one lands " +
            $"in the model but not in the entry — the published string would secure the connection " +
            $"the way it was before the change, and every deployment reading the manifest would " +
            $"follow it. The publish is failed and the partly written manifest is abandoned rather " +
            $"than completed. Recovery: call UseTls(...)/AllowInsecureTls(...) on the server while " +
            $"the application model is being built, not from a WithEnvironment(...) callback.");
    }

